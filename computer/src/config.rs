//! `config.ini` parsing and persistence.
//!
//! The parser is a pure function ([`AppConfig::parse`]) testable without file system access.
//! File I/O is handled by [`AppConfig::load`] / [`AppConfig::save`], writing atomically
//! via temporary file + rename to avoid partial writes during power loss or crashes.

use std::fmt;
use std::fs;
use std::io::Write as _;
use std::path::{Path, PathBuf};

use crate::DEFAULT_UDP_PORT;
use crate::crypto;

const CONFIG_HEADER: &str = "\
# Wake-on-LAN Computer Power Control Configuration
# udp_port: UDP listening port (default 9877)
# autostart: Launch automatically on system login (true / false)
# secret: shared command-authentication secret (32 lowercase hex; generated on first use)
";

/// Daemon configuration values.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct AppConfig {
    pub udp_port: u16,
    pub autostart: bool,
    /// Shared HMAC secret for remote commands. Empty until generated by [`Self::ensure_secret`].
    pub secret: String,
}

impl Default for AppConfig {
    fn default() -> Self {
        Self {
            udp_port: DEFAULT_UDP_PORT,
            autostart: true,
            secret: String::new(),
        }
    }
}

impl AppConfig {
    /// Parse configuration from INI text.
    ///
    /// Unknown keys, comments, blank lines, and malformed values are safely ignored,
    /// preserving defaults so older configs (e.g. containing `start_minimized`) load cleanly.
    pub fn parse(content: &str) -> Self {
        let mut config = Self::default();

        for line in content.lines() {
            let line = line.trim();
            if line.is_empty() || line.starts_with('#') || line.starts_with(';') {
                continue;
            }

            let Some((key, value)) = line.split_once('=') else {
                continue;
            };

            match key.trim().to_ascii_lowercase().as_str() {
                "port" | "udp_port" => {
                    if let Ok(port) = value.trim().parse::<u16>()
                        && port != 0
                    {
                        config.udp_port = port;
                    }
                }
                "autostart" => config.autostart = parse_bool(value.trim()),
                "secret" => config.secret = value.trim().to_owned(),
                _ => {}
            }
        }

        config
    }

    /// Generate and persist a command secret when none is configured.
    ///
    /// Old configs (no `secret=` key) load with an empty secret; the daemon calls this on
    /// startup and `--status` so the user can copy the value into the phone apps. Existing
    /// secrets are never overwritten.
    pub fn ensure_secret(&mut self, path: &Path) -> Result<(), ConfigError> {
        if !self.secret.trim().is_empty() {
            return Ok(());
        }

        let secret = generate_secret().ok_or_else(|| {
            ConfigError::new("cannot obtain random bytes from the operating system")
        })?;
        self.secret = secret;
        self.save(path)
    }

    /// Load configuration; returns default values if file does not exist or cannot be read.
    pub fn load(path: &Path) -> Self {
        match fs::read_to_string(path) {
            Ok(content) => Self::parse(&content),
            Err(_) => Self::default(),
        }
    }

    /// Atomically save configuration file.
    pub fn save(&self, path: &Path) -> Result<(), ConfigError> {
        if let Some(parent) = path.parent()
            && !parent.as_os_str().is_empty()
        {
            fs::create_dir_all(parent).map_err(|e| {
                ConfigError::new(format!(
                    "cannot create configuration directory {}: {e}",
                    parent.display()
                ))
            })?;
        }

        let temporary = temporary_path(path);
        let mut options = fs::OpenOptions::new();
        options.write(true).create(true).truncate(true);
        #[cfg(unix)]
        {
            use std::os::unix::fs::OpenOptionsExt;
            options.mode(0o600);
        }
        let mut file = options.open(&temporary).map_err(|e| {
            ConfigError::new(format!(
                "cannot create temporary configuration file {}: {e}",
                temporary.display()
            ))
        })?;
        file.write_all(self.render().as_bytes()).map_err(|e| {
            ConfigError::new(format!(
                "cannot write temporary configuration file {}: {e}",
                temporary.display()
            ))
        })?;
        file.sync_all().map_err(|e| {
            ConfigError::new(format!(
                "cannot sync temporary configuration file {}: {e}",
                temporary.display()
            ))
        })?;
        drop(file);
        #[cfg(unix)]
        {
            use std::os::unix::fs::PermissionsExt;
            fs::set_permissions(&temporary, fs::Permissions::from_mode(0o600)).map_err(|e| {
                ConfigError::new(format!(
                    "cannot set permissions on {}: {e}",
                    temporary.display()
                ))
            })?;
        }

        fs::rename(&temporary, path).map_err(|e| {
            let _ = fs::remove_file(&temporary);
            ConfigError::new(format!(
                "cannot update configuration file {}: {e}",
                path.display()
            ))
        })
    }

    /// Render configuration file content.
    pub fn render(&self) -> String {
        format!(
            "{CONFIG_HEADER}udp_port={}\nautostart={}\nsecret={}\n",
            self.udp_port, self.autostart, self.secret
        )
    }
}

/// Generate a command secret: 32 lowercase hex characters (128 bits) from the OS CSPRNG.
pub fn generate_secret() -> Option<String> {
    let mut bytes = [0u8; 16];
    if !crypto::fill_random(&mut bytes) {
        return None;
    }
    Some(crypto::hex_encode(&bytes))
}

fn parse_bool(value: &str) -> bool {
    matches!(
        value.to_ascii_lowercase().as_str(),
        "true" | "1" | "yes" | "on"
    )
}

fn temporary_path(path: &Path) -> PathBuf {
    let mut name = path.file_name().unwrap_or_default().to_os_string();
    name.push(format!(".{}.tmp", std::process::id()));
    path.with_file_name(name)
}

/// Configuration access failure.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct ConfigError {
    message: String,
}

impl ConfigError {
    fn new(message: impl Into<String>) -> Self {
        Self {
            message: message.into(),
        }
    }
}

impl fmt::Display for ConfigError {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        f.write_str(&self.message)
    }
}

impl std::error::Error for ConfigError {}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::test_support::TempDir;

    #[test]
    fn defaults_match_the_wire_protocol() {
        let config = AppConfig::default();
        assert_eq!(config.udp_port, DEFAULT_UDP_PORT);
        assert!(config.autostart);
        assert!(config.secret.is_empty());
    }

    #[test]
    fn legacy_configs_without_a_secret_load_with_an_empty_one() {
        let config = AppConfig::parse("udp_port=9000\nautostart=false\n");
        assert_eq!(config.udp_port, 9000);
        assert!(!config.autostart);
        assert!(config.secret.is_empty());
    }

    #[test]
    fn parses_secret_tolerantly() {
        assert_eq!(
            AppConfig::parse("secret=0123456789abcdef0123456789abcdef").secret,
            "0123456789abcdef0123456789abcdef"
        );
        assert_eq!(AppConfig::parse("  secret = abc123 \r\n").secret, "abc123");
        assert!(AppConfig::parse("secret=").secret.is_empty());
        assert!(AppConfig::parse("secret=   ").secret.is_empty());
    }

    #[test]
    fn parses_both_port_key_names() {
        assert_eq!(AppConfig::parse("udp_port=9000").udp_port, 9000);
        assert_eq!(AppConfig::parse("port=9001").udp_port, 9001);
    }

    #[test]
    fn ignores_invalid_values_comments_and_unknown_keys() {
        let content = "\
# comment
; another comment
start_minimized=true
udp_port=0
port=not-a-number
autostart=maybe
";
        let config = AppConfig::parse(content);
        assert_eq!(config.udp_port, DEFAULT_UDP_PORT);
        assert!(!config.autostart);
    }

    #[test]
    fn parses_boolean_spellings() {
        for value in ["true", "TRUE", "1", "yes", "on", "On"] {
            assert!(AppConfig::parse(&format!("autostart={value}")).autostart);
        }
        for value in ["false", "FALSE", "0", "no", "off", ""] {
            assert!(!AppConfig::parse(&format!("autostart={value}")).autostart);
        }
    }

    #[test]
    fn tolerates_crlf_and_extra_whitespace() {
        let config = AppConfig::parse("  udp_port = 8123 \r\n autostart = false \r\n");
        assert_eq!(config.udp_port, 8123);
        assert!(!config.autostart);
    }

    #[test]
    fn load_returns_defaults_without_creating_a_file() {
        let dir = TempDir::new("config-missing");
        let path = dir.path().join("config.ini");

        assert_eq!(AppConfig::load(&path), AppConfig::default());
        assert!(!path.exists(), "loading should not have side effects");
    }

    #[test]
    fn save_and_load_round_trip() {
        let dir = TempDir::new("config-roundtrip");
        let path = dir.path().join("config.ini");
        let config = AppConfig {
            udp_port: 9123,
            autostart: false,
            secret: "0123456789abcdef0123456789abcdef".to_owned(),
        };

        config.save(&path).expect("save config");
        assert_eq!(AppConfig::load(&path), config);

        let leftovers: Vec<_> = fs::read_dir(dir.path())
            .expect("read config dir")
            .filter_map(|entry| entry.ok())
            .filter(|entry| entry.file_name().to_string_lossy().contains(".tmp"))
            .collect();
        assert!(
            leftovers.is_empty(),
            "temp files should disappear after rename"
        );
    }

    #[cfg(unix)]
    #[test]
    fn saved_config_is_private_to_the_owner() {
        use std::os::unix::fs::PermissionsExt;

        let dir = TempDir::new("config-mode");
        let path = dir.path().join("config.ini");
        AppConfig {
            udp_port: 9877,
            autostart: false,
            secret: "0123456789abcdef0123456789abcdef".to_owned(),
        }
        .save(&path)
        .expect("save config");

        let mode = fs::metadata(&path)
            .expect("config metadata")
            .permissions()
            .mode()
            & 0o777;
        assert_eq!(mode, 0o600, "config contains a command secret");
    }

    #[test]
    fn save_overwrites_existing_file() {
        let dir = TempDir::new("config-overwrite");
        let path = dir.path().join("config.ini");
        fs::write(&path, "udp_port=1234\nautostart=false\n").expect("write old config");

        AppConfig {
            udp_port: 4321,
            autostart: true,
            secret: "fedcba9876543210fedcba9876543210".to_owned(),
        }
        .save(&path)
        .expect("overwrite config");

        let reloaded = AppConfig::load(&path);
        assert_eq!(reloaded.udp_port, 4321);
        assert!(reloaded.autostart);
        assert_eq!(reloaded.secret, "fedcba9876543210fedcba9876543210");
    }

    #[test]
    fn render_is_parseable_by_our_own_parser() {
        let config = AppConfig {
            udp_port: 9877,
            autostart: true,
            secret: "0123456789abcdef0123456789abcdef".to_owned(),
        };
        assert_eq!(AppConfig::parse(&config.render()), config);
    }

    #[test]
    fn ensure_secret_generates_and_persists_32_lowercase_hex() {
        let dir = TempDir::new("config-secret");
        let path = dir.path().join("config.ini");
        let mut config = AppConfig::default();

        config.ensure_secret(&path).expect("ensure secret");

        assert_eq!(config.secret.len(), 32);
        assert!(config.secret.bytes().all(|byte| byte.is_ascii_hexdigit()));
        assert!(!config.secret.bytes().any(|byte| byte.is_ascii_uppercase()));

        let reloaded = AppConfig::load(&path);
        assert_eq!(reloaded, config);
        assert!(
            fs::read_to_string(&path)
                .expect("read config")
                .contains(&format!("secret={}", config.secret))
        );
    }

    #[test]
    fn ensure_secret_preserves_an_existing_secret() {
        let dir = TempDir::new("config-secret-existing");
        let path = dir.path().join("config.ini");
        let mut config = AppConfig::default();
        config.ensure_secret(&path).expect("generate secret");
        let generated = config.secret.clone();

        config.ensure_secret(&path).expect("second call");
        assert_eq!(config.secret, generated);
        assert_eq!(AppConfig::load(&path).secret, generated);
    }

    #[test]
    fn ensure_secret_upgrades_legacy_configs_without_losing_values() {
        let dir = TempDir::new("config-secret-legacy");
        let path = dir.path().join("config.ini");
        fs::write(&path, "udp_port=9123\nautostart=false\n").expect("write legacy config");

        let mut config = AppConfig::load(&path);
        assert!(config.secret.is_empty());
        config.ensure_secret(&path).expect("ensure secret");

        let reloaded = AppConfig::load(&path);
        assert_eq!(reloaded.udp_port, 9123);
        assert!(!reloaded.autostart);
        assert_eq!(reloaded.secret.len(), 32);
        assert_eq!(reloaded, config);
    }

    #[test]
    fn generate_secret_matches_the_documented_shape() {
        let secret = generate_secret().expect("OS random source");
        assert_eq!(secret.len(), 32);
        assert!(secret.bytes().all(|byte| byte.is_ascii_hexdigit()));
        assert!(!secret.bytes().any(|byte| byte.is_ascii_uppercase()));
    }
}
